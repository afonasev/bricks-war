import { _electron as electron } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile, cp, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { homedir } from 'node:os';
import { sign } from 'node:crypto';
import { digest } from '../../electron/content.mjs';
const output = 'evidence/github-game-updates';
const profile = join(process.cwd(), 'build/github-update-smoke-profile');
const feed = join(process.cwd(), 'build/github-update-smoke-feed');
await mkdir(output, { recursive: true });
await rm(profile, { recursive: true, force: true }); await mkdir(profile, { recursive: true });
await rm(feed, { recursive: true, force: true }); await mkdir(feed, { recursive: true });
const env = { ...process.env, BRICKS_DESKTOP_QA_PROFILE: profile, BRICKS_DESKTOP_QA_OFFLINE: '1', BRICKS_DESKTOP_QA_FEED: feed };
const report = {};
let app;
try {
  app = await electron.launch({ args: ['.'], env });
  const page = await app.firstWindow(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.getByRole('button', { name: 'Повторить', exact: true }).waitFor();
  report.failedDiscoveryVisible = true;
  const envelope = JSON.parse(await readFile('build/desktop-content/manifest.json', 'utf8'));
  const manifest = JSON.parse(envelope.payload); manifest.sequence++;
  await cp('build/desktop-content', join(feed, String(manifest.sequence)), { recursive: true });
  const indexFile = join(feed, String(manifest.sequence), 'index.html');
  const bytes = Buffer.from((await readFile(indexFile, 'utf8')).replace('</head>', '<meta name="qa-content-release" content="B"></head>'));
  await writeFile(indexFile, bytes);
  const file = manifest.files.find(f => f.path === 'index.html'); file.size = bytes.length; file.sha256 = digest(bytes);
  const payload = JSON.stringify(manifest);
  const key = await readFile(process.env.BRICKS_CONTENT_PRIVATE_KEY ?? join(homedir(), '.config/bricks-war/content-private-key.pem'), 'utf8');
  await writeFile(join(feed, 'latest.json'), JSON.stringify({ payload, signature: sign(null, Buffer.from(payload), key).toString('base64') }));
  await page.getByRole('button', { name: 'Повторить', exact: true }).click();
  await page.getByRole('button', { name: 'Обновить', exact: true }).waitFor();
  await page.evaluate(() => localStorage.setItem('qa-github-update-retained', 'yes'));
  await page.locator('[data-destination="settings"]').click();
  assert.equal(await page.evaluate(() => window.bricksDesktop.apply()), false);
  report.safeMenuGuard = true;
  await page.locator('#settings-back').click();
  await page.getByRole('button', { name: 'Обновить', exact: true }).click();
  await page.locator('meta[name="qa-content-release"]').waitFor({ state: 'attached' });
  assert.equal(await page.evaluate(() => localStorage.getItem('qa-github-update-retained')), 'yes');
  await page.screenshot({ path: `${output}/native-updated.png` });
  report.applied = true; report.retainedSettings = true;
  assert.deepEqual(errors, []); report.pageErrors = errors;
  await app.close(); app = null;
  // Real restart with neither VPS nor fixture available; verified content remains local.
  app = await electron.launch({ args: ['.'], env: { ...env, BRICKS_DESKTOP_QA_FEED: '' } });
  const restored = await app.firstWindow();
  await restored.locator('meta[name="qa-content-release"]').waitFor({ state: 'attached' });
  assert.equal(await restored.evaluate(() => localStorage.getItem('qa-github-update-retained')), 'yes');
  await restored.getByRole('button', { name: 'Повторить', exact: true }).waitFor();
  report.offlineRestart = true;
  await writeFile(`${output}/native-smoke.json`, JSON.stringify(report, null, 2) + '\n');
  console.log(report);
} finally {
  if (app) await app.close();
  await rm(profile, { recursive: true, force: true }); await rm(feed, { recursive: true, force: true });
}
